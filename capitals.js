// Shared helpers used by both pages.
window.CapitalsUtil = {
  byCode(code) {
    code = (code || "").toUpperCase();
    return window.CAPITALS.find((c) => c.c === code) || null;
  },
  wikiTitle(c) {
    return c.w || c.cap;
  },
  flagUrl(c, w = 80) {
    return `https://flagcdn.com/w${w}/${c.c.toLowerCase()}.png`;
  },
  distanceKm(a, b) {
    const R = 6371, rad = Math.PI / 180;
    const dLat = (b.lat - a.lat) * rad, dLon = (b.lon - a.lon) * rad;
    const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLon / 2) ** 2;
    return 2 * R * Math.asin(Math.sqrt(h));
  },
  getWishlist() {
    try { return JSON.parse(localStorage.getItem("capitals-wishlist") || "[]"); } catch { return []; }
  },
  setWishlist(list) {
    try { localStorage.setItem("capitals-wishlist", JSON.stringify(list)); } catch {}
  },
  toggleWishlist(code) {
    const list = this.getWishlist();
    const i = list.indexOf(code);
    if (i >= 0) list.splice(i, 1); else list.push(code);
    this.setWishlist(list);
    return i < 0;
  },
};
